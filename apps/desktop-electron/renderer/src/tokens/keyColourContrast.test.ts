import { describe, expect, it } from "vitest";

import { NEO_DARK_EDITOR_COLORS } from "./customThemes";
import { KEY_BASE_HUES, KEY_CHIP_TINT, KEY_TOKEN_KEYS, keyTokens, mixHex } from "./keyColourDerive";
import { SELECTED_ACCENT_MIX, contrastRatio, deriveThemeTokens } from "./themeDerivation";
import { CUSTOM_PALETTES, THEMES, themeTokens } from "../test/themeFixtures";
import { parseRules, stripComments } from "../test/cssRules";
import keyColoursCss from "./keyColours.css?raw";
import chipCss from "../components/wheel/KeyChip.css?raw";

/**
 * Key chips (R4-2): a key's code reads at 4.5:1 on its own tint over the input background and
 * the panel, and 3:1 over the selected fill. Computed from the themes' own values, as
 * selectionContrast.test.ts does. keyColours.css is generated by `keyTokens()`; the last block
 * here fails when the two drift.
 */
const TOKENS_CSS = (await import("./tokens.css?raw")).default;

/** The key tokens a rule of keyColours.css declares (`declarations` lowercases names, so read them raw). */
function keysIn(selector: string): Record<string, string> {
  const rule = parseRules(stripComments(keyColoursCss)).find((r) => r.selector === selector);
  const found: Record<string, string> = {};
  for (const match of (rule?.body ?? "").matchAll(/--(key-\d+[AB]):\s*(#[0-9a-f]{6});/g)) found[match[1]!] = match[2]!;
  return found;
}

/** A theme's block in keyColours.css: its 24 tokens. */
const blockFor = (theme: string) => keysIn(`[data-theme="${theme}"]`);

/** The three backgrounds a theme's chips sit on. */
function backgroundsOf(t: Record<string, string>) {
  return {
    panel: t["bg-panel"]!,
    input: t["bg-input"]!,
    selected: mixHex(t["accent-primary"]!, t["bg-input"]!, SELECTED_ACCENT_MIX),
  };
}

/** The lowest ratio a colour reaches against its chip on the three backgrounds, each against its floor. */
function worst(colour: string, backgrounds: ReturnType<typeof backgroundsOf>): number {
  return Math.min(
    contrastRatio(colour, mixHex(colour, backgrounds.input, KEY_CHIP_TINT)) / 4.5,
    contrastRatio(colour, mixHex(colour, backgrounds.panel, KEY_CHIP_TINT)) / 4.5,
    contrastRatio(colour, mixHex(colour, backgrounds.selected, KEY_CHIP_TINT)) / 3,
  );
}

function holds(tokens: Record<string, string>, backgrounds: ReturnType<typeof backgroundsOf>): string[] {
  const failures: string[] = [];
  for (const key of KEY_TOKEN_KEYS) {
    const colour = tokens[key]!;
    for (const [name, floor] of [["input", 4.5], ["panel", 4.5], ["selected", 3]] as const) {
      const chip = mixHex(colour, backgrounds[name], KEY_CHIP_TINT);
      const ratio = contrastRatio(colour, chip);
      if (ratio < floor) failures.push(`${key} on ${name}: ${ratio.toFixed(2)} < ${floor}`);
    }
  }
  return failures;
}

describe("the chip tint", () => {
  it("is the number the stylesheet mixes", () => {
    // Round 3 (M3, D2): the key chip takes the one chip fill, --chip-fill-mix, like a Badge.
    expect(chipCss).toContain("color-mix(in srgb, var(--key) var(--chip-fill-mix), var(--chip-ground, transparent))");
    expect(TOKENS_CSS).toMatch(new RegExp(`--chip-fill-mix:\\s*${KEY_CHIP_TINT}%;`));
  });

  it("is mixed over the selected fill the way tokens.css makes it", () => {
    expect(TOKENS_CSS).toContain(`var(--accent-primary) ${SELECTED_ACCENT_MIX}%, var(--bg-input)`);
  });
});

describe.each(Object.entries(THEMES))("key chips in %s", (name, css) => {
  const t = themeTokens(css);

  it("defines all 24 key tokens", () => {
    expect(Object.keys(blockFor(name)).sort()).toEqual([...KEY_TOKEN_KEYS].sort());
  });

  it("holds the contrast rules for every key", () => {
    expect(holds(blockFor(name), backgroundsOf(t))).toEqual([]);
  });

  it("is what keyTokens() makes from the theme's own backgrounds", () => {
    expect(blockFor(name)).toEqual(keyTokens(backgroundsOf(t)));
  });
});

describe("the fallback for an unknown theme", () => {
  it("is neoDark's set, under :root", () => {
    expect(keysIn(":root")).toEqual(blockFor("neoDark"));
  });
});

describe.each([
  ["custom (derived)", NEO_DARK_EDITOR_COLORS],
  ...CUSTOM_PALETTES,
])("key chips in %s", (_name, colors) => {
  const t = deriveThemeTokens(colors);

  it("derives all 24 key tokens", () => {
    for (const key of KEY_TOKEN_KEYS) expect(t[key], key).toMatch(/^#[0-9a-f]{6}$/);
  });

  it.skipIf(/mid/.test(_name))("holds the contrast rules for every key", () => {
    expect(holds(t, backgroundsOf(t))).toEqual([]);
  });

  // A mid-tone page has no colour at 4.5:1 (holdContrast says so itself): the floor there is that
  // the derivation never leaves a key worse off than its base colour.
  it("never leaves a key reading worse than its base colour", () => {
    const backgrounds = backgroundsOf(t);
    expect(Object.keys(t).filter((k) => k.startsWith("key-")).sort()).toEqual([...KEY_TOKEN_KEYS].sort());
    for (const key of KEY_TOKEN_KEYS) {
      expect(worst(t[key]!, backgrounds), key).toBeGreaterThanOrEqual(worst(KEY_BASE_HUES[key]!, backgrounds) - 1e-9);
    }
  });
});

describe("key chip brightness (M332, D28)", () => {
  const luminance = (hex: string) => contrastRatio(hex, "#000000") * 0.05 - 0.05;

  it("draws every key of a ring at about one luminance in the base colours, so no hue shouts", () => {
    for (const ring of ["A", "B"] as const) {
      const values = KEY_TOKEN_KEYS.filter((k) => k.endsWith(ring)).map((k) => luminance(KEY_BASE_HUES[k]!));
      expect(Math.max(...values) - Math.min(...values), `${ring} ring spread`).toBeLessThan(0.03);
    }
  });

  it("keeps the B ring lighter than the A ring", () => {
    const mean = (ring: string) => {
      const v = KEY_TOKEN_KEYS.filter((k) => k.endsWith(ring)).map((k) => luminance(KEY_BASE_HUES[k]!));
      return v.reduce((a, b) => a + b, 0) / v.length;
    };
    expect(mean("B")).toBeGreaterThan(mean("A"));
  });
});

/** A colour's hue in degrees (0 for a grey). */
function hueOf(hex: string): number {
  const [r, g, b] = [1, 3, 5].map((at) => parseInt(hex.slice(at, at + 2), 16) / 255) as [number, number, number];
  const max = Math.max(r, g, b);
  const d = max - Math.min(r, g, b);
  if (d === 0) return 0;
  const h = max === r ? ((g - b) / d) % 6 : max === g ? (b - r) / d + 2 : (r - g) / d + 4;
  return (h * 60 + 360) % 360;
}

/** How far a colour's hue stands from the nearest of a theme's 24 key colours, in degrees. */
function nearestKeyGap(colour: string, keys: Record<string, string>): number {
  return Math.min(
    ...KEY_TOKEN_KEYS.map((key) => {
      const gap = Math.abs(hueOf(colour) - hueOf(keys[key]!));
      return Math.min(gap, 360 - gap);
    }),
  );
}

/** The least hue distance between a status colour and any key colour (M332, owner's pick: 12 degrees). */
const STATUS_KEY_MIN_HUE_GAP = 12;

describe.each(Object.entries(THEMES))("status colours apart from the key colours in %s (M332)", (name, css) => {
  const t = themeTokens(css);

  it.each(["accent-success", "accent-warning", "accent-info"])(
    "keeps --%s 12 degrees of hue or more from every key",
    (status) => {
      expect(nearestKeyGap(t[status]!, blockFor(name))).toBeGreaterThanOrEqual(STATUS_KEY_MIN_HUE_GAP);
    },
  );
});

describe.each([
  ["custom (derived)", NEO_DARK_EDITOR_COLORS],
  ...CUSTOM_PALETTES,
])("the derived info colour in %s (M332)", (_name, colors) => {
  // Success and warning are the user's own colours; info is the derivation's, so it keeps the rule.
  it("stands 12 degrees of hue or more from every derived key", () => {
    const t = deriveThemeTokens(colors);
    expect(nearestKeyGap(t["accent-info"]!, t)).toBeGreaterThanOrEqual(STATUS_KEY_MIN_HUE_GAP);
  });
});

describe("the key tokens", () => {
  it("are 1A to 12B", () => {
    expect(KEY_TOKEN_KEYS).toHaveLength(24);
    expect(KEY_TOKEN_KEYS[0]).toBe("key-1A");
    expect(KEY_TOKEN_KEYS[23]).toBe("key-12B");
  });
});
