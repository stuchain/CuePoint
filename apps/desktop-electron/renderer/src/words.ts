/**
 * The words CuePoint uses for a missing value (docs/user-guide/glossary.md,
 * "Words CuePoint uses").
 *
 * One dash in tables and cards, "not set" in a sentence. Every new string
 * uses these rather than "none", "empty", "No value" or "(not used)".
 */

/** A value that isn't there, in a table cell or a card. */
export const NO_VALUE = "—";

/** A value that isn't there, inside a sentence: "Now: not set". */
export const NOT_SET = "not set";
